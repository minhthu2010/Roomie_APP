ON CONFLICT (role_code) DO NOTHING;

-- Email is the account identifier and the only OTP channel.
-- phone_number is optional: it may be used to log in with a password and
-- pre-fills the post contact phone, but it is never verified by OTP.
CREATE TABLE IF NOT EXISTS users (
    user_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email             VARCHAR(254) NOT NULL,
    phone_number      VARCHAR(20),
    password_hash     TEXT,               -- NULL for Google-only accounts
    full_name         VARCHAR(150),       -- "Họ và tên" at registration
    display_name      VARCHAR(120),       -- "Tên hiển thị" in profile setup
    avatar_url        TEXT,
    account_status    VARCHAR(20) NOT NULL DEFAULT 'active'
                      CHECK (account_status IN ('active', 'suspended', 'deleted')),
    email_verified_at TIMESTAMPTZ,
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),   -- "Thành viên từ 2025"
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at        TIMESTAMPTZ,
    CHECK ((account_status = 'deleted') = (deleted_at IS NOT NULL)),
    CHECK (phone_number IS NULL OR phone_number ~ '^\+?[0-9]{9,15}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower
    ON users (LOWER(email)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_phone
    ON users (phone_number) WHERE phone_number IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_users_status ON users (account_status);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id       UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id       SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    assigned_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    assigned_by   UUID REFERENCES users(user_id) ON DELETE SET NULL,
    PRIMARY KEY (user_id, role_id)
);

-- "Tiếp tục với Google"
CREATE TABLE IF NOT EXISTS auth_identities (
    identity_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id           UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    provider          VARCHAR(30) NOT NULL CHECK (provider IN ('google')),
    provider_subject  TEXT NOT NULL,
    provider_email    VARCHAR(254),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (provider, provider_subject),
    UNIQUE (user_id, provider)
);
CREATE INDEX IF NOT EXISTS idx_auth_identities_user ON auth_identities(user_id);

-- Refresh tokens for the Android app (store a SHA-256 hash, never the token).
CREATE TABLE IF NOT EXISTS refresh_tokens (
    token_id      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash    TEXT NOT NULL UNIQUE,
    device_label  VARCHAR(120),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at    TIMESTAMPTZ NOT NULL,
    revoked_at    TIMESTAMPTZ,
    replaced_by   UUID REFERENCES refresh_tokens(token_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_active
    ON refresh_tokens(user_id) WHERE revoked_at IS NULL;

-- Firebase Cloud Messaging tokens, one row per installed app.
CREATE TABLE IF NOT EXISTS device_tokens (
    device_token_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    fcm_token       TEXT NOT NULL UNIQUE,
    platform        VARCHAR(10) NOT NULL DEFAULT 'android' CHECK (platform IN ('android', 'web')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_device_tokens_user ON device_tokens(user_id);

-- 6-digit OTP for signup, password reset and email change.
-- Store a hash of the OTP, never the raw code.
CREATE TABLE IF NOT EXISTS verification_challenges (
    challenge_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID REFERENCES users(user_id) ON DELETE CASCADE,
    destination        VARCHAR(254) NOT NULL,
    channel            VARCHAR(10) NOT NULL DEFAULT 'email' CHECK (channel = 'email'),
    purpose            VARCHAR(30) NOT NULL
                       CHECK (purpose IN ('signup', 'password_reset', 'verify_email', 'change_email')),
    code_hash          TEXT NOT NULL,
    expires_at         TIMESTAMPTZ NOT NULL,              -- UI: 05:00
    resend_available_at TIMESTAMPTZ,                      -- UI: "Gửi lại sau 00:24"
    attempts_used      SMALLINT NOT NULL DEFAULT 0 CHECK (attempts_used >= 0),
    max_attempts       SMALLINT NOT NULL DEFAULT 5 CHECK (max_attempts > 0),
    consumed_at        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (attempts_used <= max_attempts)
);
CREATE INDEX IF NOT EXISTS idx_verification_destination_purpose
    ON verification_challenges(LOWER(destination), purpose, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_verification_expiry
    ON verification_challenges(expires_at);

CREATE TABLE IF NOT EXISTS policy_acceptances (
    acceptance_id     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id           UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    policy_type       VARCHAR(30) NOT NULL
                      CHECK (policy_type IN ('terms_of_service', 'privacy_policy')),
    policy_version    VARCHAR(40) NOT NULL,
    accepted_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, policy_type, policy_version)
);

