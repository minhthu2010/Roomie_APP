-- Questions/options of a published or archived version must not change,
-- otherwise stored answers lose their meaning. Create a new version instead.
CREATE OR REPLACE FUNCTION protect_published_questionnaire()
RETURNS TRIGGER AS $$
DECLARE
    v_status TEXT;
BEGIN
    IF TG_TABLE_NAME = 'lifestyle_questions' THEN
        SELECT status INTO v_status FROM questionnaire_versions
         WHERE questionnaire_version_id = COALESCE(NEW.questionnaire_version_id, OLD.questionnaire_version_id);
    ELSE
        SELECT v.status INTO v_status
          FROM lifestyle_questions q
          JOIN questionnaire_versions v ON v.questionnaire_version_id = q.questionnaire_version_id
         WHERE q.question_id = COALESCE(NEW.question_id, OLD.question_id);
    END IF;

    IF v_status IN ('published', 'archived') THEN
        RAISE EXCEPTION 'Questionnaire version is %, create a new draft version to change questions', v_status;
    END IF;

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$ LANGUAGE plpgsql;

