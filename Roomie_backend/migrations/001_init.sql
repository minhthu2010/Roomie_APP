-- Material edits to an approved post send it back to moderation.
CREATE OR REPLACE FUNCTION require_post_reapproval_on_material_edit()
RETURNS TRIGGER AS $$
DECLARE
    target_post_id UUID;
BEGIN
    IF TG_TABLE_NAME = 'room_posts' THEN
        IF OLD.moderation_status = 'approved' AND OLD.deleted_at IS NULL AND (
            OLD.title IS DISTINCT FROM NEW.title OR
            OLD.description IS DISTINCT FROM NEW.description OR
            OLD.room_type IS DISTINCT FROM NEW.room_type OR
            OLD.monthly_rent IS DISTINCT FROM NEW.monthly_rent OR
            OLD.deposit_amount IS DISTINCT FROM NEW.deposit_amount OR
            OLD.area_m2 IS DISTINCT FROM NEW.area_m2 OR
            OLD.utility_cost_note IS DISTINCT FROM NEW.utility_cost_note OR
            OLD.roommate_expectations IS DISTINCT FROM NEW.roommate_expectations OR
            OLD.contact_phone IS DISTINCT FROM NEW.contact_phone OR
            OLD.province_code IS DISTINCT FROM NEW.province_code OR
            OLD.ward_code IS DISTINCT FROM NEW.ward_code OR
            OLD.street_address IS DISTINCT FROM NEW.street_address OR
            OLD.address_text IS DISTINCT FROM NEW.address_text OR
            OLD.latitude IS DISTINCT FROM NEW.latitude OR
            OLD.longitude IS DISTINCT FROM NEW.longitude
        ) THEN
            NEW.moderation_status := 'pending';
            NEW.submitted_at := NOW();
            NEW.reviewed_at := NULL;
            NEW.reviewed_by := NULL;
            NEW.rejection_reason := NULL;
        END IF;
        RETURN NEW;
    END IF;

    -- Photos: re-ordering or changing the cover is not a material edit.
    IF TG_TABLE_NAME = 'post_images' AND TG_OP = 'UPDATE'
       AND OLD.image_url IS NOT DISTINCT FROM NEW.image_url
       AND OLD.post_id IS NOT DISTINCT FROM NEW.post_id THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN target_post_id := OLD.post_id;
    ELSE target_post_id := NEW.post_id; END IF;

    UPDATE room_posts
       SET moderation_status = 'pending', submitted_at = NOW(), reviewed_at = NULL,
           reviewed_by = NULL, rejection_reason = NULL
     WHERE post_id = target_post_id AND moderation_status = 'approved' AND deleted_at IS NULL;

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$ LANGUAGE plpgsql;

