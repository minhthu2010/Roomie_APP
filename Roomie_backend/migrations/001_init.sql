-- Post flow (PostFlowActivity, autosaved as a draft):
--   1 basic info  2 price & amenities  3 roommate & contact
--   4 location    5 photos             6 household lifestyle test
-- Required fields are enforced only when the post leaves 'draft'.
CREATE TABLE IF NOT EXISTS room_posts (
    post_id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id              UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,

    -- step 1-2: basic info, price
    title                 VARCHAR(80),
    description           TEXT CHECK (description IS NULL OR char_length(description) <= 3000),
    room_type             VARCHAR(20)
                          CHECK (room_type IS NULL OR room_type IN ('shared_room', 'private_room', 'apartment', 'whole_house', 'studio')),
    monthly_rent          BIGINT CHECK (monthly_rent IS NULL OR monthly_rent >= 0),
    deposit_amount        BIGINT CHECK (deposit_amount IS NULL OR deposit_amount >= 0),
    area_m2               NUMERIC(6,1) CHECK (area_m2 IS NULL OR area_m2 > 0),
    utility_cost_note     TEXT,                          -- "Điện, nước & chi phí chung"
    available_from        DATE,                          -- "Ngày chuyển vào"
    current_occupants     SMALLINT CHECK (current_occupants IS NULL OR current_occupants >= 0),
    seeking_roommates     SMALLINT NOT NULL DEFAULT 1 CHECK (seeking_roommates BETWEEN 1 AND 10),

    -- step 3: roommate preferences and contact
    preferred_gender      VARCHAR(10) NOT NULL DEFAULT 'any'
                          CHECK (preferred_gender IN ('any', 'female', 'male')),
    preferred_occupation  VARCHAR(10) NOT NULL DEFAULT 'any'
                          CHECK (preferred_occupation IN ('any', 'student', 'worker')),
    smoking_allowed       BOOLEAN,                       -- chip "Không hút thuốc" => FALSE
    pets_allowed          BOOLEAN,
    roommate_expectations TEXT CHECK (roommate_expectations IS NULL OR char_length(roommate_expectations) <= 1000),
    contact_phone         VARCHAR(20) CHECK (contact_phone IS NULL OR contact_phone ~ '^\+?[0-9]{9,15}$'),
    allow_zalo            BOOLEAN NOT NULL DEFAULT TRUE,
    allow_call            BOOLEAN NOT NULL DEFAULT TRUE,

    -- step 4: location
    province_code         VARCHAR(10) REFERENCES provinces(province_code) ON DELETE RESTRICT,
    ward_code             VARCHAR(10),
    district_legacy       VARCHAR(100),                  -- old district name, display only
    street_address        VARCHAR(200),                  -- "268 Lý Thường Kiệt"
    address_text          TEXT,                          -- full display address built by backend
    landmark_id           INTEGER REFERENCES landmarks(landmark_id) ON DELETE SET NULL,
    latitude              NUMERIC(10,7) CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude             NUMERIC(10,7) CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    -- lifecycle
    draft_step            SMALLINT NOT NULL DEFAULT 1 CHECK (draft_step BETWEEN 1 AND 6),
    moderation_status     VARCHAR(20) NOT NULL DEFAULT 'draft'
                          CHECK (moderation_status IN ('draft', 'pending', 'approved', 'rejected')),
    listing_status        VARCHAR(20) NOT NULL DEFAULT 'searching'
                          CHECK (listing_status IN ('searching', 'filled', 'hidden', 'expired')),
    rejection_reason      TEXT,
    reviewed_by           UUID REFERENCES users(user_id) ON DELETE SET NULL,
    reviewed_at           TIMESTAMPTZ,
    submitted_at          TIMESTAMPTZ,
    first_published_at    TIMESTAMPTZ,                   -- "Đăng ngày 02/10/2026"
    expires_at            TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at            TIMESTAMPTZ,

    -- the ward must belong to the chosen province
    FOREIGN KEY (province_code, ward_code) REFERENCES wards(province_code, ward_code) ON DELETE RESTRICT,
    CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CHECK (moderation_status <> 'approved' OR (reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL)),
    CHECK (moderation_status <> 'rejected' OR (reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL)),
    CHECK (moderation_status <> 'pending' OR submitted_at IS NOT NULL),
    CHECK (allow_zalo OR allow_call),
    -- A post outside 'draft' must be complete.
    CONSTRAINT chk_room_posts_complete_when_submitted CHECK (
        moderation_status = 'draft' OR (
            title IS NOT NULL AND char_length(btrim(title)) > 0 AND
            description IS NOT NULL AND
            room_type IS NOT NULL AND
            monthly_rent IS NOT NULL AND
            province_code IS NOT NULL AND
            street_address IS NOT NULL AND
            contact_phone IS NOT NULL
        )
    )
);

