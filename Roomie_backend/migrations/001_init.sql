-- ============================================================
-- ROOMIE - PostgreSQL database schema v3
-- Scope: Android app (XML + Java) + React admin website
-- Backend: Node.js + Express + node-postgres
-- PostgreSQL 13+ (needs contrib extensions pgcrypto, unaccent)
--
-- v3 changes vs v2 (aligned with Roomie_APP UI, commit 55b1ec5):
--  * Drafts: post fields are nullable while moderation_status='draft'
--    (UI shows "Bài đăng chưa đặt tiêu đề", autosave per step) and
--    become required on submit. draft_step stores the post-flow step.
--  * room_posts: area_m2, roommate_expectations, preferred_occupation,
--    contact_phone + allow_zalo + allow_call (replaces post_contacts),
--    room_type values match the filter chips, title <= 80 chars.
--  * Money is BIGINT (VND has no decimals; node-pg still returns BIGINT
--    as string - see note I).
--  * Locations: province + ward codes (Vietnam two-level administration
--    since 01/07/2025). district_legacy kept only for display.
--  * Landmarks (universities...) for "Gần ĐH Bách Khoa" chips/suggestions.
--  * Questionnaire seed = the 8 questions in HabitQuizActivity, grouped
--    into the 4 groups shown on the compatibility screen; options carry
--    a score for matching and an optional room-test label.
--  * user_profiles: occupation, birth_year (age on poster card), gender,
--    living area codes; users: full_name (register) + display_name.
--  * user_settings matches the notification / privacy switches.
--  * reports / feedback categories match the UI; feedback subject,
--    contact email, <= 3 photos; report <= 3 photos.
--  * New: device_tokens (FCM), refresh_tokens (JWT), post_contact_clicks
--    ("lượt quan tâm"), deferrable display_order uniques.
--  * Fixes: moderation log actor, updated_at triggers on answer tables,
--    users status/deleted_at consistency, re-approval trigger ignores
--    pure re-ordering of photos, public view lists explicit columns,
--    accent-insensitive full-text search.
-- ============================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- unaccent() is only STABLE; an IMMUTABLE wrapper is needed for
-- generated columns and indexes.
CREATE OR REPLACE FUNCTION immutable_unaccent(input TEXT)
RETURNS TEXT
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, input) $$;

-- ------------------------------------------------------------
-- 0. Administrative areas and landmarks
