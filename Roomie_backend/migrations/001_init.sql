CREATE TABLE IF NOT EXISTS roles (
    role_id       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code     VARCHAR(30) NOT NULL UNIQUE,
    role_name     VARCHAR(80) NOT NULL
);

INSERT INTO roles (role_code, role_name)
