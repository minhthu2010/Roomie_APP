CREATE TABLE IF NOT EXISTS user_lifestyle_answers (
    user_id                    UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    questionnaire_version_id   BIGINT NOT NULL,
    question_id                BIGINT NOT NULL,
    answer_value               JSONB NOT NULL CHECK (jsonb_typeof(answer_value) = 'object'),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, questionnaire_version_id, question_id),
    FOREIGN KEY (questionnaire_version_id, question_id)
        REFERENCES lifestyle_questions(questionnaire_version_id, question_id)
        ON DELETE RESTRICT
