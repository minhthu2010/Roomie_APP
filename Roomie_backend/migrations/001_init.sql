-- Progress is version-specific; current_step is not tied to a fixed count.
-- started_at/completed_at give "thời gian hoàn tất" and "Cập nhật dd/mm".
CREATE TABLE IF NOT EXISTS user_lifestyle_test_progress (
    user_id                    UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    questionnaire_version_id   BIGINT NOT NULL
                               REFERENCES questionnaire_versions(questionnaire_version_id)
                               ON DELETE RESTRICT,
    current_step               INTEGER NOT NULL DEFAULT 1 CHECK (current_step >= 1),
    is_completed               BOOLEAN NOT NULL DEFAULT FALSE,
    started_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at               TIMESTAMPTZ,
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, questionnaire_version_id),
    CHECK (is_completed = (completed_at IS NOT NULL))
);

