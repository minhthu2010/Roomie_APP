ON CONFLICT (province_code) DO NOTHING;

CREATE TABLE IF NOT EXISTS wards (
    ward_code     VARCHAR(10) PRIMARY KEY,
    province_code VARCHAR(10) NOT NULL REFERENCES provinces(province_code) ON DELETE RESTRICT,
    ward_name     VARCHAR(100) NOT NULL,
    UNIQUE (province_code, ward_name),
    UNIQUE (province_code, ward_code)
);

-- Universities, workplaces, well-known places used by search suggestions
-- ("Gợi ý trường học"), chips ("Gần ĐH Bách Khoa") and distance labels.
CREATE TABLE IF NOT EXISTS landmarks (
    landmark_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landmark_type VARCHAR(20) NOT NULL DEFAULT 'university'
                  CHECK (landmark_type IN ('university', 'workplace', 'other')),
    name          VARCHAR(180) NOT NULL,
    short_name    VARCHAR(60),
    address_text  TEXT,
    province_code VARCHAR(10) NOT NULL REFERENCES provinces(province_code) ON DELETE RESTRICT,
    ward_code     VARCHAR(10) REFERENCES wards(ward_code) ON DELETE SET NULL,
    latitude      NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude     NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (province_code, name)
);
CREATE INDEX IF NOT EXISTS idx_landmarks_search
    ON landmarks USING GIN (to_tsvector('simple', immutable_unaccent(name || ' ' || coalesce(short_name, ''))));

